package edu.uptc.enrollments.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.LocalDateTime;
import java.util.Objects;

@Entity
@Table(name = "enrollment_status_history")
public class EnrollmentStatusHistory {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "enrollment_id", nullable = false)
    private Enrollment enrollment;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 30)
    private EnrollmentStatus status;

    @Column(name = "date", nullable = false)
    private LocalDateTime date;

    @Column(name = "reason", nullable = false, length = 255)
    private String reason;

    public EnrollmentStatusHistory() {
    }

    public EnrollmentStatusHistory(Enrollment enrollment, EnrollmentStatus status, LocalDateTime date, String reason) {
        this.enrollment = enrollment;
        this.status = status;
        this.date = date;
        this.reason = reason;
    }

    public EnrollmentStatusHistory(Long id, Enrollment enrollment, EnrollmentStatus status, LocalDateTime date, String reason) {
        this.id = id;
        this.enrollment = enrollment;
        this.status = status;
        this.date = date;
        this.reason = reason;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Enrollment getEnrollment() {
        return enrollment;
    }

    public void setEnrollment(Enrollment enrollment) {
        this.enrollment = enrollment;
    }

    public EnrollmentStatus getStatus() {
        return status;
    }

    public void setStatus(EnrollmentStatus status) {
        this.status = status;
    }

    public LocalDateTime getDate() {
        return date;
    }

    public void setDate(LocalDateTime date) {
        this.date = date;
    }

    public String getReason() {
        return reason;
    }

    public void setReason(String reason) {
        this.reason = reason;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        EnrollmentStatusHistory that = (EnrollmentStatusHistory) o;
        return Objects.equals(id, that.id);
    }

    @Override
    public int hashCode() {
        return Objects.hash(id);
    }

    @Override
    public String toString() {
        return "EnrollmentStatusHistory{" +
                "id=" + id +
                ", status=" + status +
                ", date=" + date +
                ", reason='" + reason + '\'' +
                '}';
    }
}
